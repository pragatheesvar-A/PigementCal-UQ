"""RED through the NORMAL live pipeline, with no special-casing anywhere.

virtual signal (generated by frontend/src/lib/virtualSensor.ts: low perfusion + INTERMEDIATE noise, seed 42; stored as a fixture and checked against
the generator by the frontend test) -> /api/live/analyze (PPG analysis: SQI, PI, SpO2, motion) -> /api/reliability/predict (the existing rule engine).
Nothing here sets a state: the engine decides from the computed values and the unchanged thresholds. VIRTUAL HARDWARE SIMULATION - NOT REAL MEASUREMENTS.
"""
import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.config import RELIABILITY_CONFIG
from app.main import app

FIXTURE = Path(__file__).parent / "fixtures" / "virtual_low_perfusion_intermediate_noise_seed42.json"
VDEV = "Virtual ESP32 + Virtual MAX30102 (simulation)"
client = TestClient(app)


def _window(doc, end_s):
    a, b = round((end_s - 10) * 100), round(end_s * 100)
    return {"ir": doc["ir"][a:b], "red": doc["red"][a:b], "t": [i / 100 for i in range(a, b)], "source": "virtual"}


def _pipeline(doc, end_s, ita=35.0):
    a = client.post("/api/live/analyze", json=_window(doc, end_s))
    assert a.status_code == 200, a.text
    a = a.json()
    if a["pi_estimate"] is None or a["spo2"]["estimate"] is None:
        return a, None
    r = client.post("/api/reliability/predict", json={"spo2": a["spo2"]["estimate"], "pi": a["pi_estimate"], "ita": ita, "signal_quality": a["signal_quality"],
                                                       "motion": a["motion_state"], "device": a["device"], "sqi": a["sqi"], "motion_score": a["motion_score"]})
    assert r.status_code == 200, r.text
    return a, r.json()


@pytest.fixture(scope="module")
def doc():
    d = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert d["scenario"] == "low_perfusion_noisy" and d["seed"] == 42 and len(d["ir"]) == len(d["red"]) == d["samples"] >= 3300
    return d


def test_thresholds_are_the_unchanged_production_values():
    c = RELIABILITY_CONFIG
    assert (c.points_low_pi, c.points_very_low_pi, c.points_moderate_signal, c.points_medium_motion, c.red_points) == (1, 2, 1, 1, 3)
    assert c.pi_very_low_below == 0.5 and c.pi_low_below == 1.0


@pytest.mark.parametrize("end_s", [15, 18, 24, 30, 33])
def test_intermediate_noise_with_low_perfusion_reaches_RED_through_the_real_rule_engine(doc, end_s):
    a, r = _pipeline(doc, end_s)
    assert a["source"] == "virtual" and a["device"] == VDEV
    assert a["signal_quality"] == "MODERATE" and a["pi_estimate"] is not None and a["pi_estimate"] < RELIABILITY_CONFIG.pi_very_low_below   # computed, not injected
    assert r is not None and r["reliability_state"] == "RED" and r["points"] == 3
    codes = [x["code"] for x in r["reasons"]]
    assert {"low_pi", "very_low_pi", "moderate_signal", "multiple_factors"} <= set(codes)
    assert "abstain" not in codes


def test_the_same_scenario_is_not_always_red_because_the_window_changes_what_the_analysis_sees(doc):
    states = {}
    for end in (12, 15, 18, 21, 24, 27, 30, 33):
        a, r = _pipeline(doc, end)
        states[end] = r["reliability_state"] if r else a["reliability_impact"]["state_hint"]
    assert states[12] == "AMBER"                       # signal still GOOD in that window: 2 points
    assert states[21] == states[27] == "ABSTAIN"       # SQI falls to POOR in those windows: PI withheld, the engine abstains
    assert list(states.values()).count("RED") >= 4


def test_the_virtual_label_does_not_change_the_outcome(doc):
    a, r = _pipeline(doc, 18)
    body = {**_window(doc, 18), "source": "esp32"}
    real = client.post("/api/live/analyze", json=body).json()
    for k in ("sqi", "signal_quality", "motion_state", "motion_score", "pi_estimate", "spo2", "pulse_rate_estimate"):
        assert real[k] == a[k]
    r2 = client.post("/api/reliability/predict", json={"spo2": real["spo2"]["estimate"], "pi": real["pi_estimate"], "ita": 35.0, "signal_quality": real["signal_quality"],
                                                        "motion": real["motion_state"], "device": real["device"], "sqi": real["sqi"], "motion_score": real["motion_score"]}).json()
    assert r2["reliability_state"] == r["reliability_state"] and r2["points"] == r["points"]


def test_clean_virtual_signal_gives_a_computed_motion_zero_not_a_missing_value():
    import math
    ir = [90000 * (1 - 0.01 * math.sin(2 * math.pi * 1.2 * i / 100)) for i in range(1000)]
    a = client.post("/api/live/analyze", json={"ir": ir, "fs": 100, "source": "virtual", "invert": False}).json()
    assert a["motion_score"] == 0.0 and a["motion_source"] == "estimated" and a["motion_state"] == "LOW"
